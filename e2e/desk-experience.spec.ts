test('remediation independent reading shows the whole bound archive, not just its short citation', async ({ page }) => {
  const expected = await page.evaluate(async () => {
    const { createExampleCourse } = await import('/src/learning/exampleCourse.ts')
    const { updateCourse, loadCourseSnapshot, savePracticeBundle } = await import('/src/learning/repository.ts')
    const { learningBase } = await import('/src/learning/model.ts')
    const { db } = await import('/src/store/db.ts')
    const { archiveHashPayload } = await import('/src/learning/archiveValidation.ts')
    const { canonicalizeJson } = await import('/packages/analysis-contracts/src/index.ts')
    const { sha256Hex } = await import('/src/analysis/fingerprint.ts')
    const { startRemediationJourney } = await import('/src/learning/learningLoop.ts')
    const course = await updateCourse({ ...await createExampleCourse(), example: false })
    let s = await loadCourseSnapshot(course.id)
    const archive = s.archives[0]; const quiz = archive.artifacts.find((a) => a.kind === 'quiz')!
    if (quiz.kind !== 'quiz') throw new Error('fixture quiz missing')
    quiz.payload.questions[0].citations = [{ version: 1, provenance: 'source', sourceId: archive.sources[0].id, start: 0, end: 10 }]
    archive.contentHash = await sha256Hex(canonicalizeJson(archiveHashPayload(archive)))
    await db.learningRecords.put(archive); s = await loadCourseSnapshot(course.id)
    const attempt = { ...learningBase(course.id), kind: 'attempt' as const, question: s.points[0].questionRefs[0], answer: 1, submittedAt: Date.now(), learningDate: '2026-10-16', answerRevealed: false, origin: 'practice' as const }
    await savePracticeBundle(attempt, { ...learningBase(course.id), kind: 'assessment', attemptId: attempt.id, outcome: 'failure', difficulty: 'again', selfAssessmentComplete: true })
    const journey = await startRemediationJourney(await loadCourseSnapshot(course.id), attempt.id)
    window.dispatchEvent(new CustomEvent('msz:learning-open', { detail: { courseId: course.id, view: 'today', journeyId: journey.id } }))
    return archive.sources[0].text
  })
  const layer = page.getByRole('dialog', { name: '原文补学', exact: true })
  await expect(layer.getByRole('button', { name: '继续下一步' })).toBeEnabled()
  await layer.getByRole('button', { name: '打开伊希斯新手引导' }).click()
  await layer.getByRole('button', { name: '进入独立阅读', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '独立阅读', exact: true }).locator('[data-reader-text]')).toHaveText(expected)
})
