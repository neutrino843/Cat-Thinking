async function seed(page: Page, short = false) {
  await page.evaluate(async (short) => {
    const { createExampleCourse } = await import('/src/learning/exampleCourse.ts')
    const { updateCourse, loadCourseSnapshot } = await import('/src/learning/repository.ts')
    const c = await updateCourse({ ...await createExampleCourse(), example: false })
    const s = await loadCourseSnapshot(c.id); const q = s.points[0].questionRefs[short ? 2 : 0]
    window.dispatchEvent(new CustomEvent('msz:learning-open', { detail: { courseId: c.id, view: 'practice', questionKey: `${q.archiveId}/${q.artifactId}/${q.questionId}` } }))
  }, short)
  await expect(page.locator('.focused-question')).toBeVisible()
}
