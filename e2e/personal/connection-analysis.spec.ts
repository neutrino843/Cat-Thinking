import { expect, test, type Page } from '@playwright/test'
import { resetStore, waitForApp } from '../helpers'
import { FIXTURE_TEXT } from '../../services/analysis-service/test/fixtures/fakeAnalysisProvider'

const settings = (page: Page) => page.getByRole('dialog', { name: '连接你的 AI' })
const analysis = (page: Page) => page.getByRole('dialog', { name: 'AI 学习分析' })
test('填写连接经真实网关和数据库生成五类结果，刷新不重付费，暂停与删除保留结果', async ({ page, request }) => {
  await resetStore(page); await waitForApp(page)
  await page.getByRole('button', { name: 'AI 设置', exact: true }).click()
  await expect(settings(page).getByLabel('AI 服务', { exact: true })).toBeEnabled()
  await settings(page).getByLabel('AI 服务', { exact: true }).selectOption('custom')
  await settings(page).getByLabel('API 服务地址').fill('http://127.0.0.1:9876/v1/chat/completions')
  await settings(page).getByLabel('API 密钥', { exact: true }).fill('synthetic-personal-key-not-real')
  await settings(page).getByRole('button', { name: '读取可用模型' }).click()
  await expect(settings(page)).toContainText('已读取账号模型列表')
  await settings(page).getByRole('button', { name: 'synthetic-model', exact: true }).click()
  await settings(page).getByRole('button', { name: '保存并连接', exact: true }).click()
  await expect(settings(page)).toContainText('已连接，可以开始分析')
  await expect(settings(page).getByLabel('API 密钥', { exact: true })).toHaveValue('')
  const headers = { authorization: `Bearer ${process.env.ANALYSIS_GATEWAY_TOKEN ?? ''}` }
  const counts = async () => (await request.get('http://127.0.0.1:8790/__synthetic/status', { headers })).json()
  expect((await counts()).generationCalls).toBe(0)
  await settings(page).getByRole('button', { name: '回到文档', exact: true }).click()
  await page.locator('input[type=file][accept^=".txt"]').setInputFiles({ name: '公开测试原文.txt', mimeType: 'text/plain', buffer: Buffer.from(FIXTURE_TEXT) })
  const imported = page.getByRole('dialog', { name: '从文档生成可编辑导图' })
  await imported.getByRole('button', { name: '创建可编辑导图' }).click()
  await expect(imported).toBeHidden()
  await page.getByRole('button', { name: 'AI 分析', exact: true }).click()
  await expect(analysis(page)).toContainText('合成测试环境')
  for (const name of ['导图', '测验', '知识整理']) await analysis(page).getByRole('checkbox', { name, exact: true }).check()
  await analysis(page).getByRole('button', { name: '生成所选内容', exact: true }).click()
  await expect(analysis(page)).toContainText('任务：分析完成', { timeout: 20_000 })
  for (const name of ['摘要结果', '大纲结果', '导图结果', '测验结果', '知识整理结果']) {
    await expect(analysis(page).getByRole('region', { name, exact: true })).toBeVisible()
  }
  await expect(analysis(page)).toContainText('费用以服务商账单为准')
  expect((await counts()).generationCalls).toBe(6)
  await page.screenshot({ path: 'test-results/personal-five-artifacts.png' })
  await page.reload(); await waitForApp(page)
  await page.getByRole('button', { name: 'AI 分析', exact: true }).click()
  await expect(analysis(page)).toContainText('任务：分析完成')
  expect((await counts()).generationCalls).toBe(6)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'AI 设置', exact: true }).click()
  await expect(settings(page)).toContainText('已连接，可以开始分析')
  await settings(page).getByRole('button', { name: '暂停新分析', exact: true }).click()
  await expect(settings(page)).toContainText('已暂停')
  const caps = await (await request.get('/api/analysis/v1/capabilities')).json()
  expect(caps.acceptsRuns).toBe(false)
  await settings(page).getByRole('button', { name: '删除连接与密钥', exact: true }).click()
  await settings(page).getByRole('button', { name: '确认删除连接', exact: true }).click()
  await expect.poll(async () => (await (await request.get('/api/analysis/v1/personal/settings')).json()).configured).toBe(false)
  expect((await counts()).generationCalls).toBe(6)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'AI 分析', exact: true }).click()
  await expect(analysis(page).getByRole('region', { name: '摘要结果' })).toContainText(FIXTURE_TEXT)
})
