test('today task decisions survive reload, fill freed capacity and can be undone without AI calls', async ({ page }) => {
  const calls: string[] = []; page.on('request', (request) => { if (request.method() === 'POST') calls.push(request.url()) })
  await seed(page)
  await page.evaluate(async () => {
    const { createCourse, saveEntity } = await import('/src/learning/repository.ts'); const { learningBase } = await import('/src/learning/model.ts')
    for (const name of ['排期课程乙', '排期课程丙', '排期课程丁', '排期课程戊', '排期课程己', '排期课程庚']) { const course = await createCourse({ name, dailyMinutes: 20 }); await saveEntity({ ...learningBase(course.id), kind: 'point', title: `${name}知识`, definition: '个人知识', chapter: '', aliases: [], notes: '', sourceRefs: [], questionRefs: [], status: 'active', goalIncluded: true }, null) }
  })
  await page.reload()
  await page.locator('.focus-plan > summary').click()
  await page.getByLabel('当天总时间（分钟）', { exact: true }).fill('20'); await page.getByRole('button', { name: '保存当天容量', exact: true }).click()
  const tasks = page.locator('.study-task-list li')
  await expect(tasks).toHaveCount(2)
  const firstTitle = await tasks.nth(0).getByRole('heading', { level: 3 }).innerText()
  const secondTitle = await tasks.nth(1).getByRole('heading', { level: 3 }).innerText()
  const firstCourse = (await tasks.nth(0).locator('p').innerText()).split(' · ')[0]
  await page.getByRole('button', { name: `稍后做：${firstCourse} · ${firstTitle}`, exact: true }).click()
  await expect(tasks.nth(0).getByRole('heading', { level: 3 })).toHaveText(secondTitle)
  await page.reload(); await page.locator('.focus-plan > summary').click(); await expect(tasks.nth(1).getByRole('heading', { level: 3 })).toHaveText(firstTitle)
  await page.getByRole('button', { name: `恢复默认排序：${firstCourse} · ${firstTitle}`, exact: true }).click()
  await expect(tasks.nth(0).getByRole('heading', { level: 3 })).toHaveText(firstTitle)
  await page.getByRole('button', { name: `稍后做：${firstCourse} · ${firstTitle}`, exact: true }).click()
  await page.getByRole('button', { name: `明天再做：${firstCourse} · ${firstTitle}`, exact: true }).click()
  await expect(tasks.getByRole('heading', { name: firstTitle, exact: true })).toHaveCount(0)
  await expect(tasks).toHaveCount(2)
  await page.getByRole('button', { name: /未安排内容与原因/ }).click()
  await expect(page.getByText('你选择了明天再做；今天不占用容量，也不修改原复习日期。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: `恢复今日安排：${firstCourse} · ${firstTitle}`, exact: true }).click()
  await expect(tasks.getByRole('heading', { name: firstTitle, exact: true })).toHaveCount(1)
  await page.getByLabel('当天总时间（分钟）', { exact: true }).fill('60'); await page.getByRole('button', { name: '保存当天容量', exact: true }).click()
  await expect(tasks).toHaveCount(5)
  await page.getByRole('button', { name: '查看其余 1 项今日任务', exact: true }).click()
  await expect(tasks).toHaveCount(6)
  expect(calls).toEqual([])
})
