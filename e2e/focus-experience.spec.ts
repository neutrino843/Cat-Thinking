const text = '第一章 植物的能量\n\n光合作用把光能转化为化学能，并释放氧气。\n\n植物需要适合的光照条件。'
const study = (page: Page) => page.getByRole('main', { name: '原文入门学习' })
async function importText(page: Page, guided = true) {
  if (guided) await page.getByRole('button', { name: /开始使用 · 伊希斯/ }).click()
  await page.getByLabel('导入课程资料', { exact: true }).setInputFiles({ name: '我的资料.txt', mimeType: 'text/plain', buffer: Buffer.from(text) })
  await page.getByRole('button', { name: '创建可编辑导图', exact: true }).click()
  if (!guided) await page.getByRole('button', { name: /直接开始学习/ }).click()
  await expect(study(page).getByRole('region', { name: '第一道入门题' })).toBeVisible()
}
