import { expect, test, type Page } from '@playwright/test'

async function seedCourse(page: Page, confirmed = true, automatic = false) {
  return page.evaluate(async ({ confirmed, automatic }) => {
    const { db, saveDocumentBundle } = await import('/src/store/db.ts')
    const { localArtifactFixtures } = await import('/src/test/localArtifactFixtures.ts')
    const { createCourse, createLearningArchive, loadCourseSnapshot, saveEntity } = await import('/src/learning/repository.ts')
    const f = await localArtifactFixtures()
    await saveDocumentBundle(f.doc, [f.source]); await db.analysisTasks.add(f.task)
    const created = await createCourse({ name: '课程闭环', dailyMinutes: 30, dailyQuestionLimit: 10 })
    if (automatic) await saveEntity({ ...created, automaticReviews: true }, created.revision)
    const archive = await createLearningArchive({ courseId: created.id, docId: f.doc.id, runId: f.task.runId, artifacts: [f.mindmap, f.quiz], title: '公开学习资料' })
    if (confirmed) {
      const snapshot = await loadCourseSnapshot(created.id)
      for (const point of snapshot.points) await saveEntity({ ...point, status: 'active', goalIncluded: true, questionRefs: point.questionRefs.map((r) => ({ ...r, confirmed: true })) }, point.revision)
    }
    return { courseId: created.id, archiveId: archive.id, originDocId: f.doc.id, sourceId: f.source.id }
  }, { confirmed, automatic })
}

